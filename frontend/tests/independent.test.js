import { expect, it } from 'vitest';
import { subscribeStatus } from '../src/statusBridge.js';
it('S2/S3: disabled controls yield before engine observation and resident GPU stays yielded', async () => {
  document.body.innerHTML = '<section class="model-panel"><button id="load-model"></button><p id="model-status">Ready</p></section><p id="migration-status">Idle</p>';
  let engine = null;
  const snapshots = [];
  const stop = subscribeStatus(document, () => engine, s => snapshots.push(s));
  const tick = () => new Promise(resolve => queueMicrotask(resolve));
  await tick();
  expect(snapshots.at(-1)).toMatchObject({ busy: false, suspended: false });
  const button = document.getElementById('load-model');
  button.disabled = true;
  await tick();
  expect(snapshots.at(-1)).toMatchObject({ busy: true, suspended: true });
  engine = {};
  button.disabled = false;
  await tick();
  expect(snapshots.at(-1)).toMatchObject({ busy: false, suspended: true });
  engine = null;
  document.getElementById('model-status').textContent = 'Selection changed';
  await tick();
  expect(snapshots.at(-1).suspended).toBe(true);
  expect(document.getElementById('load-model')).toBe(button);
  stop();
  const count = snapshots.length;
  button.disabled = true;
  await tick();
  expect(snapshots).toHaveLength(count);
  document.body.innerHTML = '';
});
